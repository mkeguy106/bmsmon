"""Pure-ASGI middlewares wrapped around the whole app.

Pure ASGI (not BaseHTTPMiddleware) on purpose: they must see WebSocket handshakes too
and must never buffer a streaming body. The ORDER is set in app.main.create_app —
read the comment there before adding another.
"""

import asyncio
import logging

import asyncpg
from fastapi import HTTPException
from starlette.datastructures import Headers
from starlette.responses import JSONResponse, PlainTextResponse
from starlette.types import ASGIApp, Message, Receive, Scope, Send

from app.config import settings

logger = logging.getLogger(__name__)

# C1 (cross-plan contract): every response this app generates carries this header, so
# the phone can tell an app-level rejection (a real 4xx from a route) from Traefik's own
# 404/502 while bmsmon-api is stopped, starting or unhealthy — which it used to treat as
# "server rejects this batch" and delete the outbox (DATA-14). Traefik never adds it.
API_MARKER_HEADER = "X-Bmsmon-Api"
API_MARKER_VALUE = "1"
_MARKER = (API_MARKER_HEADER.lower().encode("latin-1"), API_MARKER_VALUE.encode("latin-1"))
# Response-start messages: plain HTTP, the WebSocket 101 accept, and a WebSocket denial
# response. A pre-accept websocket.close carries no headers (uvicorn answers it with a
# bare 403), so it cannot be marked — nothing that matters to the phone uses /ws.
_STARTS = frozenset({"http.response.start", "websocket.accept",
                     "websocket.http.response.start"})


class ApiMarkerMiddleware:
    """Stamps X-Bmsmon-Api: 1 on every response start. Must stay the OUTERMOST user
    middleware so responses generated by inner middlewares (e.g. the body cap's 413)
    are marked too."""

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] not in ("http", "websocket"):
            await self.app(scope, receive, send)
            return

        async def send_marked(message: Message) -> None:
            if message["type"] in _STARTS:
                headers = [(k, v) for k, v in (message.get("headers") or [])
                           if k.lower() != _MARKER[0]]
                headers.append(_MARKER)
                message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_marked)


_CLOSED_MARKERS = ("pool is closed", "pool is closing", "pool is not initialized", "connection is closed")


def is_db_unavailable(exc: BaseException) -> bool:
    """True when exc means the database cannot be reached right now (restart, refused
    connection, exhausted or closed pool, acquire timeout) rather than a bug. Such a
    failure is transient, so the phone must retry it instead of treating it as a
    deterministic fault."""
    if isinstance(exc, (asyncpg.exceptions.PostgresConnectionError,
                        asyncpg.exceptions.TooManyConnectionsError,
                        # SQLSTATE class 57 (admin/crash shutdown, cannot connect now,
                        # query canceled) and 55P03 (a pg_dump holding a lock): all
                        # transient, so err toward a retry, never a skipped row.
                        asyncpg.exceptions.OperatorInterventionError,
                        asyncpg.exceptions.LockNotAvailableError,
                        # SQLSTATE class 53 (disk full, out of memory, too many
                        # connections) and 25006 (a read-only standby or a disk-full
                        # read-only fallback): the DB is up but cannot take writes. A
                        # marked 500 here would read as a deterministic fault and let the
                        # phone skip good rows while the DB is sick (DATA-22 review).
                        asyncpg.exceptions.InsufficientResourcesError,
                        asyncpg.exceptions.ReadOnlySQLTransactionError,
                        # Class 58 (the server's own I/O / system errors), 28xxx (credentials
                        # no longer accepted, e.g. mid password rotation) and 3D000 (database
                        # gone): the DB is unusable for EVERY request, not for this sample.
                        # XX000 (internal error) stays a 500.
                        asyncpg.exceptions.PostgresSystemError,
                        asyncpg.exceptions.InvalidAuthorizationSpecificationError,
                        asyncpg.exceptions.InvalidCatalogNameError)):
        return True
    if isinstance(exc, asyncpg.exceptions.InterfaceError):
        msg = str(exc).lower()
        return any(m in msg for m in _CLOSED_MARKERS)
    # OSError covers ConnectionRefusedError and (3.11+) asyncio.TimeoutError from acquire.
    return isinstance(exc, (OSError, asyncio.TimeoutError))


async def marked_internal_error(request, exc: Exception):
    """Catch-all handler. Starlette's ServerErrorMiddleware sits OUTSIDE every user
    middleware, so its default 500 never passes ApiMarkerMiddleware; this handler stamps
    the marker itself. DB unavailability becomes a marked 503 + Retry-After (transient:
    retry); anything else is a marked 500 (a crash) whose body matches Starlette's
    default. The exception is still re-raised (and logged by uvicorn) after the response
    is sent."""
    headers = {API_MARKER_HEADER: API_MARKER_VALUE}
    if is_db_unavailable(exc):
        logger.warning("database unavailable (%s) on %s %s", type(exc).__name__,
                       request.method, request.url.path)
        return JSONResponse({"detail": "database unavailable"}, status_code=503,
                            headers={**headers, "Retry-After": "30"})
    return PlainTextResponse("Internal Server Error", status_code=500, headers=headers)


class BodySizeLimitMiddleware:
    """SEC-17 / C4: ONE request-body cap (settings.max_body_bytes) for every HTTP route.

    A declared Content-Length over the cap is refused with 413 before the route (and any
    rate limiter) runs. A body without (or lying about) Content-Length is counted as it
    streams, and the read that crosses the cap raises HTTPException(413), which the
    ExceptionMiddleware turns into the same response. Nothing past the cap is buffered.
    This is what bounds /api/v1/enroll, whose pydantic body FastAPI would otherwise read
    whole, pre-auth. The device routes keep their own caps in _read_body as a second line.
    """

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        limit = settings.max_body_bytes  # read per request: tests override it
        declared = Headers(scope=scope).get("content-length")
        if declared is not None:
            try:
                too_big = int(declared) > limit
            except ValueError:
                too_big = False  # malformed header: the streamed count below still bounds it
            if too_big:
                response = JSONResponse({"detail": "body too large"}, status_code=413)
                await response(scope, receive, send)
                return
        received = 0

        async def capped_receive() -> Message:
            nonlocal received
            message = await receive()
            if message["type"] == "http.request":
                received += len(message.get("body", b""))
                if received > limit:
                    raise HTTPException(413, "body too large")
            return message

        await self.app(scope, capped_receive, send)
